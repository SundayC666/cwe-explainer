class ConfigError(RuntimeError):
    """Raised when required configuration is missing or unusable."""


@dataclass(frozen=True)
class Config:
    """Runtime configuration, assembled entirely from environment variables."""

    api_key: str
    base_url: str
    model_name: str
    port: int


def load_config() -> Config:
    """Read configuration from the environment, failing fast on problems.

    DUKE_API_KEY is required. Everything else has a sensible default.
    """
    api_key = os.environ.get("DUKE_API_KEY", "").strip()
    if not api_key:
        raise ConfigError(
            "DUKE_API_KEY is not set.\n"
            "  Local:  copy .env.example to .env and fill in your key.\n"
            "  Docker: pass it at runtime, e.g. "
            "`docker run -e DUKE_API_KEY=sk-... ...` or `--env-file .env`.\n"
            "The key is never baked into the image."
        )

    base_url = os.environ.get("DUKE_BASE_URL", "").strip() or DEFAULT_BASE_URL
    model_name = os.environ.get("MODEL_NAME", "").strip() or DEFAULT_MODEL

    raw_port = os.environ.get("PORT", "").strip() or str(DEFAULT_PORT)
    try:
        port = int(raw_port)
    except ValueError as exc:
        raise ConfigError(f"PORT must be an integer, got {raw_port!r}.") from exc

    return Config(api_key=api_key, base_url=base_url, model_name=model_name, port=port)


