"""Generate cwe_owasp_map.py from the official OWASP Top 10:2025 pages.

Run once: uv run python build_mapping.py
"""

import re
import time
import urllib.request

BASE = "https://owasp.org/Top10/2025/"
UA = "Mozilla/5.0 (Macintosh; Intel Mac OS X 10_15_7)"

PAGES = {
    "A01:2025 - Broken Access Control": "A01_2025-Broken_Access_Control/",
    "A02:2025 - Security Misconfiguration": "A02_2025-Security_Misconfiguration/",
    "A03:2025 - Software Supply Chain Failures": "A03_2025-Software_Supply_Chain_Failures/",
    "A04:2025 - Cryptographic Failures": "A04_2025-Cryptographic_Failures/",
    "A05:2025 - Injection": "A05_2025-Injection/",
    "A06:2025 - Insecure Design": "A06_2025-Insecure_Design/",
    "A07:2025 - Authentication Failures": "A07_2025-Authentication_Failures/",
    "A08:2025 - Software or Data Integrity Failures": "A08_2025-Software_or_Data_Integrity_Failures/",
    "A09:2025 - Security Logging and Alerting Failures": "A09_2025-Security_Logging_and_Alerting_Failures/",
    "A10:2025 - Mishandling of Exceptional Conditions": "A10_2025-Mishandling_of_Exceptional_Conditions/",
}

CWE_LINK = re.compile(r"cwe\.mitre\.org/data/definitions/(\d+)\.html")


def fetch(path: str) -> str:
    req = urllib.request.Request(BASE + path, headers={"User-Agent": UA})
    return urllib.request.urlopen(req).read().decode("utf-8")


mapping: dict[str, str] = {}

for category, path in PAGES.items():
    html = fetch(path)
    # Parse only below the heading: CWEs named in the prose above it are
    # illustrative examples, not the authoritative list.
    tail = html.split("List of Mapped CWEs", 1)[-1]
    ids = sorted({int(n) for n in CWE_LINK.findall(tail)})
    print(f"{category}: {len(ids)} CWEs")
    for n in ids:
        mapping[f"CWE-{n}"] = category
    time.sleep(0.5)   # be polite to the server

with open("cwe_owasp_map.py", "w") as f:
    f.write('"""Generated by build_mapping.py from https://owasp.org/Top10/2025/\n\n')
    f.write('Do not edit by hand — re-run the script instead.\n"""\n\n')
    f.write("CWE_TO_OWASP_2025: dict[str, str] = {\n")
    for cwe, cat in sorted(mapping.items(), key=lambda kv: int(kv[0][4:])):
        f.write(f'    "{cwe}": "{cat}",\n')
    f.write("}\n")

print(f"\nWrote {len(mapping)} entries to cwe_owasp_map.py")