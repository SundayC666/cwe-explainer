# The built-in footer renders in the browser's language, which would make a
# screen recording inconsistent — hide it. Gradio 6 takes css in launch(), not
# in the Blocks constructor.
HIDE_FOOTER_CSS = "footer { display: none !important; }"


def build_interface(config: Config, client: OpenAI) -> gr.Blocks:
    """Construct the Gradio UI."""

    # If MODEL_NAME points at something not in the curated list, surface it
    # anyway so the configured default is always selectable.
    choices = list(MODEL_CHOICES)
    if config.model_name not in choices:
        choices.insert(0, config.model_name)

    def analyze(snippet: str, model: str) -> tuple[str, str, str]:
        """Run one analysis and return (summary, accepted, rejected) markdown."""
        if not snippet or not snippet.strip():
            return "**Paste a code snippet to analyze.**", "", ""

        try:
            raw, notes = call_model(
                client,
                model,
                snippet,
                temperature=0,
                max_tokens=2000,
            )
        except Exception as exc:  # surfaced in the UI rather than crashing
            return (
                f"**Request to `{model}` failed.**\n\n```\n{exc}\n```",
                "",
                "",
            )

        accepted, rejected = validate_findings(raw, snippet)
        summary = summarize(accepted, rejected)
        return (
            render_summary(summary, model, notes),
            render_accepted(accepted),
            render_rejected(rejected),
        )

    with gr.Blocks(title="CWE Vulnerability Explainer") as demo:
        gr.Markdown(
            "# CWE Vulnerability Explainer\n"
            "Paste a code snippet. It is sent to an LLM through the Duke AI "
            "Gateway, and every finding the model returns is validated locally "
            "— schema, CWE allowlist, severity enum, line-number bounds, "
            "duplicates — before it is displayed. OWASP categories are "
            "additionally cross-checked against the **Top 10:2025** edition "
            "and corrected in place, since models trained before that release "
            "still emit the 2021 numbering.\n\n"
            "**This is a triage aid for human reviewers, not a scanner.** "
            "It produces both false positives and false negatives. Switch to "
            "one of the `nano` models to watch the validation layer reject "
            "hallucinated CWE IDs."
        )

        with gr.Row():
            with gr.Column(scale=3):
                code_input = gr.Code(
                    value=EXAMPLE_SNIPPET,
                    language="python",
                    label="Source code snippet",
                    lines=24,
                )
            with gr.Column(scale=1):
                model_dropdown = gr.Dropdown(
                    choices=choices,
                    value=config.model_name,
                    label="Model",
                    info="Weak models are included on purpose — they "
                    "demonstrate the filter.",
                )
                submit = gr.Button("Analyze", variant="primary")

        summary_output = gr.Markdown(label="Summary")

        with gr.Tab("Validated findings"):
            accepted_output = gr.Markdown()
        with gr.Tab("Filtered out"):
            rejected_output = gr.Markdown()

        submit.click(
            fn=analyze,
            inputs=[code_input, model_dropdown],
            outputs=[summary_output, accepted_output, rejected_output],
        )

    return demo


def main() -> None:
    try:
        config = load_config()
    except ConfigError as exc:
        print(f"Configuration error: {exc}", file=sys.stderr)
        raise SystemExit(1)

    client = build_client(config)
    demo = build_interface(config, client)
    # 0.0.0.0 so the app is reachable from outside the container, and from a
    # Hugging Face Docker Space.
    demo.launch(server_name="0.0.0.0", server_port=config.port, css=HIDE_FOOTER_CSS)


if __name__ == "__main__":
    main()
