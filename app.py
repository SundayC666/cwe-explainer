@dataclass
class Finding:
    """A single model finding that passed every validation check."""

    vulnerability_type: str
    cwe_id: str
    cwe_name: str
    owasp_category: str
    severity: str
    line_numbers: list[int]
    explanation: str
    remediation: str
    # Set only when the OWASP cross-check overwrote the model's label. The
    # original claim is preserved for the reviewer; the note explains why it
    # was replaced. Both stay None on findings that needed no correction.
    owasp_claimed: str | None = None
    validation_note: str | None = None


@dataclass
class RejectedFinding:
    """A model finding that failed validation, with the reason why."""

    raw: Any
    reason: str
    # Set when the *whole response* failed to parse, rather than one finding.
    # Used so the summary does not misreport a parse failure as "1 finding".
    is_parse_error: bool = False


@dataclass
class Summary:
    """Counts shown in the UI summary line."""

    returned: int = 0
    accepted: int = 0
    rejected: int = 0
    # Accepted findings whose OWASP category was overwritten. These were kept,
    # not filtered — the weakness was real, only the label was wrong.
    corrected: int = 0
    # Accepted tier-2 findings: a real CWE that is not on the curated
    # allowlist. Counted separately because these were kept, not filtered —
    # they are just held to a weaker standard of verification.
    unverified: int = 0
    reason_counts: dict[str, int] = field(default_factory=dict)
    # True when the whole response was unusable. Kept separate from the
    # counts so a legitimate empty array ("no vulnerabilities") is not
    # reported as a parse failure.
    parse_failed: bool = False


# ---------------------------------------------------------------------------
# JSON extraction — models love to wrap JSON in prose and markdown fences
# ---------------------------------------------------------------------------

_FENCE_RE = re.compile(r"```(?:json|JSON)?\s*(.*?)```", re.DOTALL)


def strip_code_fences(text: str) -> str:
    """Return the contents of the first markdown code fence, or the input."""
    match = _FENCE_RE.search(text)
    return match.group(1).strip() if match else text.strip()


def extract_json_payload(text: str) -> Any:
    """Parse the model's response into Python data, tolerating common noise.

    Tries, in order: the fence-stripped text as-is; the widest ``[...]`` span;
    the widest ``{...}`` span. Raises ValueError if nothing parses.
    """
    cleaned = strip_code_fences(text)

    candidates: list[str] = [cleaned]

    # Some models prepend "Here are the findings:" before the array.
    for opener, closer in (("[", "]"), ("{", "}")):
        start = cleaned.find(opener)
        end = cleaned.rfind(closer)
        if start != -1 and end > start:
            candidates.append(cleaned[start : end + 1])

    for candidate in candidates:
        try:
            return json.loads(candidate)
        except (json.JSONDecodeError, TypeError):
            continue

    raise ValueError("response was not valid JSON")


def coerce_to_finding_list(payload: Any) -> list[Any]:
    """Normalize the parsed payload into a list of candidate findings.

    Accepts a bare array, or an object wrapping the array under a common key.
    """
    if isinstance(payload, list):
        return payload
    if isinstance(payload, dict):
        for key in ("findings", "vulnerabilities", "results", "issues"):
            value = payload.get(key)
            if isinstance(value, list):
                return value
        # A single finding returned as a lone object.
        if any(k in payload for k in REQUIRED_FIELDS):
            return [payload]
    raise ValueError(
        "expected a JSON array of findings, got "
        f"{type(payload).__name__}"
    )


# ---------------------------------------------------------------------------
# Normalization helpers
# ---------------------------------------------------------------------------

_CWE_RE = re.compile(r"^\s*(?:cwe)?[\s\-_:]*(\d{1,5})\s*$", re.IGNORECASE)


def normalize_cwe_id(raw: str) -> str | None:
    """Turn 'cwe_89', '89', 'CWE 89' into 'CWE-89'. None if unparseable."""
    match = _CWE_RE.match(raw)
    return f"CWE-{int(match.group(1))}" if match else None


def normalize_line_numbers(raw: Any) -> tuple[list[int], str | None]:
    """Coerce a line-number list to ints.

    Returns (line_numbers, error). Accepts ints and integer-valued strings,
    because models frequently emit ``["12", "13"]``.
    """
    if not isinstance(raw, list):
        return [], f"line_numbers must be a list, got {type(raw).__name__}"
    if not raw:
        return [], "line_numbers is empty; a finding must cite at least one line"

    numbers: list[int] = []
    for item in raw:
        if isinstance(item, bool):  # bool is a subclass of int — reject it
            return [], "line_numbers contains a boolean"
        if isinstance(item, int):
            numbers.append(item)
        # isdecimal, not isdigit: isdigit accepts characters like "²" that
        # int() then refuses, which would crash validation.
        elif isinstance(item, str) and item.strip().lstrip("-").isdecimal():
            numbers.append(int(item.strip()))
        else:
            return [], f"line_numbers contains a non-integer value: {item!r}"
    return numbers, None


