SEVERITY_ORDER = {s: i for i, s in enumerate(VALID_SEVERITIES)}
SEVERITY_MARK = {
    "CRITICAL": "🔴",
    "HIGH": "🟠",
    "MEDIUM": "🟡",
    "LOW": "🔵",
    "INFO": "⚪",
}


def render_summary(summary: Summary, model: str, notes: Iterable[str]) -> str:
    """Render the always-visible summary line."""
    if summary.parse_failed:
        headline = (
            f"**`{model}` returned 0 usable findings.** "
            "The response could not be parsed as JSON."
        )
    elif summary.returned == 0:
        # A well-formed empty array. Per the README this is not evidence the
        # code is safe — only that the model reported nothing.
        headline = f"**`{model}` reported no findings.**"
    else:
        # "unverified" is qualified inside the passed count rather than listed
        # alongside "filtered out", because those findings were kept — leaving
        # it as a bare tally would read as a third disposition.
        passed = f"{summary.accepted} passed validation"
        if summary.unverified:
            if summary.unverified == 1:
                passed += " (1 with an unverified CWE)"
            else:
                passed += f" ({summary.unverified} with unverified CWEs)"
        parts = [
            passed,
            f"{summary.rejected} filtered out",
        ]
        if summary.corrected:
            noun = "category" if summary.corrected == 1 else "categories"
            parts.append(f"{summary.corrected} OWASP {noun} corrected")
        headline = (
            f"**`{model}` returned {summary.returned} finding(s) — "
            f"{', '.join(parts)}.**"
        )

    lines = [headline]
    if summary.reason_counts:
        breakdown = ", ".join(
            f"{count} × {reason}"
            for reason, count in sorted(
                summary.reason_counts.items(), key=lambda kv: -kv[1]
            )
        )
        lines.append(f"Filtered because: {breakdown}.")
    for note in notes:
        lines.append(f"_Note: {note}_")
    return "\n\n".join(lines)


def render_accepted(findings: list[Finding]) -> str:
    """Render validated findings as readable markdown."""
    if not findings:
        return "_No findings survived validation._"

    ordered = sorted(
        findings, key=lambda f: (SEVERITY_ORDER[f.severity], f.line_numbers[0])
    )
    blocks: list[str] = []
    for finding in ordered:
        lines = ", ".join(str(n) for n in finding.line_numbers)
        # Corrections are shown inline rather than hidden, so the reviewer can
        # see that the label was changed and judge it for themselves.
        note_line = (
            f"⚠️ *{finding.validation_note}*  \n" if finding.validation_note else ""
        )
        blocks.append(
            f"### {SEVERITY_MARK[finding.severity]} {finding.severity} — "
            f"{finding.vulnerability_type}\n"
            f"**{finding.cwe_id}** · {finding.cwe_name}  \n"
            f"**OWASP:** {finding.owasp_category}  \n"
            f"{note_line}"
            f"**Line(s):** {lines}\n\n"
            f"**Why:** {finding.explanation}\n\n"
            f"**Fix:** {finding.remediation}"
        )
    return "\n\n---\n\n".join(blocks)


def render_rejected(rejected: list[RejectedFinding]) -> str:
    """Render filtered findings and the reason each was dropped."""
    if not rejected:
        return "_Nothing was filtered out._"

    blocks: list[str] = []
    for item in rejected:
        raw = item.raw
        preview = json.dumps(raw, indent=2) if not isinstance(raw, str) else raw
        if len(preview) > 1200:
            preview = preview[:1200] + "\n… (truncated)"
        blocks.append(f"**{item.reason}**\n\n```json\n{preview}\n```")
    return "\n\n---\n\n".join(blocks)


