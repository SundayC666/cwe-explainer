"""
CWE Vulnerability Explainer
===========================

A triage aid that asks an LLM (via the Duke AI Gateway) to identify suspected
security vulnerabilities in a source code snippet, then *validates the model's
answer locally* before any of it is shown to the user.

The validation layer is the point of this application. LLMs routinely invent
plausible-looking CWE identifiers, cite line numbers that do not exist, and
emit malformed JSON. Everything the model returns is treated as untrusted
input and must survive `validate_findings()` before it reaches the screen.

This is NOT an authoritative scanner. See the limitations section of README.md.
"""

