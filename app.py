def check_owasp_mapping(cwe_id: str, claimed: str) -> tuple[str, str | None]:
    """Cross-check a model's OWASP category against the 2025 mapping.

    Unlike the CWE allowlist, a mismatch here is never grounds for rejection.
    The weakness the model found can be entirely real while its OWASP label is
    simply from the previous edition of the Top 10.

    Args:
        cwe_id: An already-normalized, already-allowlisted ID like "CWE-89".
        claimed: The raw ``owasp_category`` string the model returned.

    Returns:
        (category, note). ``category`` is what should be displayed; ``note`` is
        None when nothing needed correcting, otherwise a reviewer-facing
        explanation of what was changed and why.
    """
    official = CWE_TO_OWASP_2025.get(cwe_id)

    # The Top 10 does not cover every CWE, and the generated table only holds
    # the ones it does. A missing entry means this CWE is outside the Top 10's
    # scope (or absent from the table) — that is a gap on our side, not
    # evidence the model invented anything. Pass the claim through untouched.
    if official is None:
        return claimed, None

    claimed_clean = claimed.strip()

    # Compare only the category code (A01, A05, ...). The rest of the string
    # varies harmlessly between sources — en-dash vs hyphen, "Injection" vs
    # "Injection Flaws", extra whitespace — and none of that is a real
    # mismatch worth flagging to a reviewer.
    claimed_code = claimed_clean[:3].upper()
    if claimed_code == official[:3].upper():
        # Codes agree. Still return the official string so the displayed label
        # is canonical even when the model wrote "A01:2021 - ...".
        return official, None

    if "2021" in claimed_clean and claimed_code in LEGACY_2021_CODES:
        # Stale edition: a real category, just from the previous numbering.
        note = (
            f"Model reported {claimed_clean}, which is OWASP Top 10:2021 "
            f"numbering. Under the 2025 edition {cwe_id} is {official}."
        )
    else:
        # Not a recognizable legacy code — the model was guessing.
        note = (
            f"Model reported {claimed_clean}, which does not match the "
            f"official OWASP Top 10:2025 mapping. {cwe_id} is {official}."
        )

    return official, note


def validate_findings(
    raw_response: str,
    snippet: str,
) -> tuple[list[Finding], list[RejectedFinding]]:
    """Validate an LLM response against the snippet it claims to describe.

    Checks performed, in order, per finding:
      1. The response parses as JSON (fences stripped, prose tolerated).
      2. The finding is an object with every required field present.
      3. Each field has the correct type.
      4. ``cwe_id`` normalizes to a CWE known to either the curated allowlist
         (tier 1) or the generated OWASP table (tier 2, accepted but flagged
         as unverified). Known to neither is rejected as invented.
      5. ``severity`` is one of CRITICAL / HIGH / MEDIUM / LOW / INFO.
      6. Every cited line number falls inside the submitted snippet.
      7. The finding is not a duplicate of one already accepted
         (same CWE, same line).
      8. ``owasp_category`` is cross-checked against the 2025 mapping. This
         step corrects rather than rejects — see check_owasp_mapping().

    Returns:
        (accepted, rejected) — rejected entries each carry a human-readable
        reason. A single entry with ``is_parse_error=True`` means the whole
        response was unusable.
    """
    accepted: list[Finding] = []
    rejected: list[RejectedFinding] = []

    total_lines = len(snippet.splitlines())

    # --- Step 1: parse -----------------------------------------------------
    try:
        payload = extract_json_payload(raw_response)
        candidates = coerce_to_finding_list(payload)
    except ValueError as exc:
        rejected.append(
            RejectedFinding(
                raw=raw_response,
                reason=f"Could not parse the model response: {exc}.",
                is_parse_error=True,
            )
        )
        return accepted, rejected

    # (cwe_id, line) pairs already claimed by an accepted finding.
    seen_pairs: set[tuple[str, int]] = set()

    for index, candidate in enumerate(candidates, start=1):
        label = f"Finding #{index}"

        # --- Step 2 & 3: shape, required fields, types --------------------
        if not isinstance(candidate, dict):
            rejected.append(
                RejectedFinding(
                    candidate,
                    f"{label}: expected a JSON object, got "
                    f"{type(candidate).__name__}.",
                )
            )
            continue

        missing = [f for f in REQUIRED_FIELDS if f not in candidate]
        if missing:
            rejected.append(
                RejectedFinding(
                    candidate,
                    f"{label}: missing required field(s): {', '.join(sorted(missing))}.",
                )
            )
            continue

        type_errors = [
            f"{name} should be {expected[0].__name__}, got "
            f"{type(candidate[name]).__name__}"
            for name, expected in REQUIRED_FIELDS.items()
            if not isinstance(candidate[name], expected)
        ]
        if type_errors:
            rejected.append(
                RejectedFinding(candidate, f"{label}: {'; '.join(type_errors)}.")
            )
            continue

        # --- Step 4: CWE recognition (three tiers) ------------------------
        # The allowlist is a curated subset, not a census of real CWEs, so
        # absence from it is not by itself evidence of hallucination. A CWE
        # that appears in the generated OWASP table is corroborated by an
        # independent source and is kept, flagged as unverified rather than
        # silently trusted or wrongly discarded.
        raw_cwe = candidate["cwe_id"]
        cwe_id = normalize_cwe_id(raw_cwe)
        if cwe_id is None:
            rejected.append(
                RejectedFinding(
                    candidate,
                    f"{label}: cwe_id {raw_cwe!r} is not a recognizable CWE identifier.",
                )
            )
            continue

        if cwe_id in CWE_ALLOWLIST:
            # Tier 1: curated. Use the official name we hold for it.
            cwe_name = CWE_ALLOWLIST[cwe_id]
            unverified_note: str | None = None
        elif cwe_id in CWE_TO_OWASP_2025:
            # Tier 2: real, but uncurated. We have no vetted name for it, and
            # nothing here corroborates the severity the model assigned.
            cwe_name = cwe_id
            unverified_note = (
                f"{cwe_id} is a real CWE but is outside my curated allowlist, "
                "so its name and severity are unverified."
            )
        else:
            # Tier 3: unknown to both sources — treat as invented.
            rejected.append(
                RejectedFinding(
                    candidate,
                    f"{label}: {cwe_id} is neither on the curated CWE allowlist "
                    "nor in the OWASP Top 10:2025 mapping — treating it as a "
                    "hallucinated identifier.",
                )
            )
            continue

        # --- Step 5: severity enum ----------------------------------------
        severity = str(candidate["severity"]).strip().upper()
        if severity not in VALID_SEVERITIES:
            rejected.append(
                RejectedFinding(
                    candidate,
                    f"{label}: severity {candidate['severity']!r} is not one of "
                    f"{', '.join(VALID_SEVERITIES)}.",
                )
            )
            continue

        # --- Step 6: line numbers in range --------------------------------
        line_numbers, line_error = normalize_line_numbers(candidate["line_numbers"])
        if line_error:
            rejected.append(RejectedFinding(candidate, f"{label}: {line_error}."))
            continue

        out_of_range = [n for n in line_numbers if n < 1 or n > total_lines]
        if out_of_range:
            rejected.append(
                RejectedFinding(
                    candidate,
                    f"{label}: cites line(s) "
                    f"{', '.join(str(n) for n in out_of_range)} but the snippet "
                    f"has {total_lines} line(s).",
                )
            )
            continue

        # --- Step 7: deduplicate ------------------------------------------
        # A finding is a duplicate when every (CWE, line) pair it reports has
        # already been claimed by an accepted finding.
        pairs = {(cwe_id, n) for n in line_numbers}
        if pairs and pairs <= seen_pairs:
            rejected.append(
                RejectedFinding(
                    candidate,
                    f"{label}: duplicate — {cwe_id} was already reported on "
                    f"line(s) {', '.join(str(n) for n in sorted(line_numbers))}.",
                )
            )
            continue

        # --- Step 8: OWASP category cross-check ---------------------------
        # Deliberately non-fatal. A stale or wrong category is corrected in
        # place, never a reason to drop a finding.
        claimed_owasp = candidate["owasp_category"].strip()
        owasp_category, owasp_note = check_owasp_mapping(cwe_id, claimed_owasp)

        # A tier-2 finding can also carry a stale OWASP label. Both notes are
        # relevant to the reviewer, so neither is allowed to shadow the other.
        note_parts = [note for note in (unverified_note, owasp_note) if note]
        validation_note = " ".join(note_parts) if note_parts else None

        seen_pairs |= pairs
        accepted.append(
            Finding(
                vulnerability_type=candidate["vulnerability_type"].strip(),
                cwe_id=cwe_id,
                cwe_name=cwe_name,
                owasp_category=owasp_category,
                severity=severity,
                line_numbers=sorted(set(line_numbers)),
                explanation=candidate["explanation"].strip(),
                remediation=candidate["remediation"].strip(),
                owasp_claimed=claimed_owasp if owasp_note else None,
                validation_note=validation_note,
            )
        )

    return accepted, rejected


def summarize(
    accepted: list[Finding], rejected: list[RejectedFinding]
) -> Summary:
    """Build the counts for the UI summary line."""
    parse_failed = any(r.is_parse_error for r in rejected)
    per_finding_rejections = [r for r in rejected if not r.is_parse_error]

    reason_counts: dict[str, int] = {}
    for item in per_finding_rejections:
        # Bucket by the phrase after the "Finding #n: " prefix, trimmed to a
        # short category so the summary stays readable.
        reason_counts[_reason_bucket(item.reason)] = (
            reason_counts.get(_reason_bucket(item.reason), 0) + 1
        )

    return Summary(
        returned=0 if parse_failed else len(accepted) + len(per_finding_rejections),
        accepted=len(accepted),
        rejected=len(per_finding_rejections),
        # validation_note is no longer OWASP-specific — a tier-2 finding has
        # one too — so corrections are counted off owasp_claimed, which is set
        # only when the OWASP label was actually overwritten.
        corrected=sum(1 for finding in accepted if finding.owasp_claimed),
        unverified=sum(
            1 for finding in accepted if finding.cwe_id not in CWE_ALLOWLIST
        ),
        reason_counts=reason_counts,
        parse_failed=parse_failed,
    )


def _reason_bucket(reason: str) -> str:
    """Collapse a detailed rejection reason into a short category label."""
    lowered = reason.lower()
    if "allowlist" in lowered or "recognizable cwe" in lowered:
        return "unrecognized CWE ID"
    if "line(s)" in lowered and "snippet has" in lowered:
        return "line number out of range"
    if "duplicate" in lowered:
        return "duplicate finding"
    # Checked before "severity": a finding missing the severity field names it
    # in the reason, and that is a missing field, not an invalid value.
    if "missing required field" in lowered:
        return "missing required field"
    if "severity" in lowered:
        return "invalid severity"
    if "line_numbers" in lowered:
        return "malformed line_numbers"
    return "schema violation"


